// Builds the .htaccess that a LiteSpeed/Apache host needs to serve the static
// export the way Vercel served it: same URLs, same redirects, same canonical
// host. The redirect list is read out of next.config.ts so the two cannot drift.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const config = readFileSync(join(root, "next.config.ts"), "utf8");

// { source: "/d/x", destination: "/d/y", permanent: true }
const redirects = [...config.matchAll(
  /\{\s*source:\s*"([^"]+)"\s*,\s*destination:\s*"([^"]+)"\s*,\s*permanent:\s*(true|false)\s*,?\s*\}/g
)].map(([, source, destination, permanent]) => ({ source, destination, permanent: permanent === "true" }));

if (redirects.length === 0) throw new Error("no redirects parsed from next.config.ts — refusing to write a half-built .htaccess");

const HTTP_SAFE = process.env.HTTP_SAFE === "1";

const host = new URL(readFileSync(join(root, "lib/site.ts"), "utf8").match(/SITE_URL\s*=\s*"([^"]+)"/)[1]).host;

const lines = [
`# Generated by scripts/make-htaccess.mjs — do not hand-edit.
# Regenerate after changing redirects in next.config.ts.

Options -Indexes

<IfModule mod_rewrite.c>
RewriteEngine On

# The export writes both d/foo.html and a d/foo/ directory of RSC payloads.
# Apache would 301 /d/foo -> /d/foo/ because the directory exists, silently
# changing every URL on the site. This turns that behaviour off.
DirectorySlash Off

# --- canonical host: https + www ---------------------------------------
# Split into two single-condition rules on purpose. Mixing AND and OR in one
# RewriteCond chain is ambiguous across servers, and LiteSpeed does not honour
# a standalone "RewriteRule ^\\.well-known/ - [L]" passthrough the way Apache
# does — verified against the live host, where the ACME path still 301'd.
#
# Every rule below therefore carries its own .well-known exclusion. If an ACME
# challenge is redirected, Let's Encrypt cannot validate the domain, no
# certificate is issued, and the https redirect then makes the site
# permanently unreachable.
${HTTP_SAFE ? "# (https/www canonical rules omitted: HTTP_SAFE cutover mode)" : `RewriteCond %{REQUEST_URI} !^/\\.well-known/
RewriteCond %{HTTPS} off
RewriteRule ^(.*)$ https://${host}/$1 [R=301,L]

RewriteCond %{REQUEST_URI} !^/\\.well-known/
RewriteCond %{HTTP_HOST} !^${host.replace(/\./g, "\\.")}$ [NC]
RewriteRule ^(.*)$ https://${host}/$1 [R=301,L]`}
`,
"# --- content redirects carried over from next.config.ts --------------------"
];

for (const r of redirects) {
  lines.push(`RedirectMatch ${r.permanent ? 301 : 302} ^${r.source}/?$ ${HTTP_SAFE ? "" : `https://${host}`}${r.destination}`);
}

lines.push(`
# --- a directory with no page of its own is a 404, not a merry-go-round -----
# /d and /s are directories of per-page payloads with no page at those paths.
# mod_dir adds a trailing slash to a directory request, the rule below strips
# it off again, and the two spin: curl gives up, and so does a crawler.
#
# The .html condition is the one that matters, and leaving it out took the
# whole site down for a minute: /d/dua-yunus is ALSO a directory of payloads,
# so a rule that 404s directories without an index 404s every entry, situation
# and hadith page on the site. Only a directory with no page of its own —
# nothing at X.html and nothing at X/index.html — is the dead end this catches.
# It also has to keep its hands off anything ending in a slash, or /d/foo/
# stops redirecting to /d/foo and starts 404ing instead. Those go to the rule
# below first and come back here without the slash if there is nothing at them.
RewriteCond %{REQUEST_URI} !/$
RewriteCond %{DOCUMENT_ROOT}%{REQUEST_URI} -d
RewriteCond %{DOCUMENT_ROOT}%{REQUEST_URI}.html !-f
RewriteCond %{DOCUMENT_ROOT}%{REQUEST_URI}/index.html !-f
RewriteRule ^ - [R=404,L]

# --- trailing slash is not canonical: strip it BEFORE the rewrite below -----
# This has to run first. If the clean-URL rule ran first it would happily
# serve /d/foo/ as 200, leaving the same page live on two URLs.
RewriteCond %{REQUEST_URI} !^/$
RewriteRule ^(.+)/$ /$1 [R=301,L]

# --- clean URLs: serve /d/foo from d/foo.html ------------------------------
# No !-d guard here on purpose: d/foo IS a directory of RSC payloads, and
# requiring "not a directory" would stop this firing for every entry page.
RewriteCond %{REQUEST_FILENAME} !-f
RewriteCond %{DOCUMENT_ROOT}/$1.html -f
RewriteRule ^(.+)$ /$1.html [L]
</IfModule>

ErrorDocument 404 /404.html

# --- compression: the hadith pages are megabytes of markup ------------------
<IfModule mod_filter.c>
AddOutputFilterByType DEFLATE text/html text/plain text/css text/xml \\
  application/javascript application/json application/xml image/svg+xml
</IfModule>

# --- caching ---------------------------------------------------------------
<IfModule mod_expires.c>
ExpiresActive On
# Hashed build assets never change under the same name.
<FilesMatch "\\.(js|css|woff2)$">
  ExpiresDefault "access plus 1 year"
  Header set Cache-Control "public, immutable"
</FilesMatch>
# HTML must revalidate so a redeploy is seen promptly.
<FilesMatch "\\.html$">
  ExpiresDefault "access plus 0 seconds"
  Header set Cache-Control "public, max-age=0, must-revalidate"
</FilesMatch>
<FilesMatch "\\.(png|jpg|jpeg|svg|ico)$">
  ExpiresDefault "access plus 30 days"
</FilesMatch>
</IfModule>

<IfModule mod_headers.c>
Header set X-Content-Type-Options "nosniff"
Header set Referrer-Policy "strict-origin-when-cross-origin"
</IfModule>

AddType text/plain .txt
AddDefaultCharset UTF-8

# next/og writes this file without an extension, so Apache sends it with no
# Content-Type and every social scraper rejects the preview image.
<Files "opengraph-image">
  ForceType image/png
</Files>`);

writeFileSync(join(root, "out", ".htaccess"), lines.join("\n") + "\n");
console.log(`wrote out/.htaccess — canonical host ${host}, ${redirects.length} content redirects`);
